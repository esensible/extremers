// ---- licences
const LICENSED = ["@rollup/browser", "@babel/standalone", "babel-preset-solid", "babel-plugin-jsx-dom-expressions", "@babel/helper-module-imports", "html-entities", "parse5", "entities", "terser", "@jridgewell/source-map", "@jridgewell/trace-mapping", "@jridgewell/gen-mapping", "@jridgewell/sourcemap-codec", "@jridgewell/resolve-uri", "@jridgewell/set-array", "csso", "css-tree", "mdn-data", "source-map-js", "@rollup/plugin-html", "acorn", "solid-js", "seroval", "seroval-plugins", "csstype"];
for (const name of LICENSED) {
  const dir = join(NM, name);
  if (!existsSync(dir)) continue;
  const f = ["LICENSE", "LICENSE.md", "LICENSE.txt", "license", "LICENCE"].find((x) => existsSync(join(dir, x)));
  const text = f ? readFileSync(join(dir, f), "utf8") : `${name} ${pkg(name).version}: licence "${pkg(name).license}" (no licence file in the package)\n`;
  const rel = `LICENSES/${name.replace("/", "__")}.txt`;
  put(rel, text, { pkgName: name, from: f || "package.json", how: "licence text" });
}

// ---- VERSIONS.json
const toolchain = Object.fromEntries(Object.keys(JSON.parse(readFileSync("package.json", "utf8")).dependencies).sort().map((n) => [n, pkg(n).version]));
const builtWith = Object.fromEntries(["rollup", "@rollup/plugin-commonjs", "@rollup/plugin-node-resolve", "@rollup/plugin-json", "terser"].map((n) => [n, pkg(n).version]));
const files = Object.fromEntries(Object.keys(record).sort().map((k) => [k, record[k]]));
const total = Object.entries(record).filter(([k]) => !k.startsWith("LICENSES/")).reduce((n, [, v]) => n + v.bytes, 0);
const mine = { recipe: "studio/lib/build/package.json + build.mjs (see its header)", node: process.version, packages: toolchain, builtWith, totalBytes: total, files };
// the other keys kept as they are, in their place; ours replaced (or added)
const merged = { ...prev };
for (const k of OWN) merged[k] = mine[k];
writeFileSync(VERSIONS, JSON.stringify(merged, null, 2) + "\n");
const others = Object.keys(merged).filter((k) => !OWN.includes(k));
console.log(`VERSIONS.json: kept ${others.length ? others.join(", ") : "no other keys"}`);
console.log(`studio/lib: ${Object.keys(record).length} files, ${total} bytes (without licences)`);
for (const [k, v] of Object.entries(files)) if (!k.startsWith("LICENSES/")) console.log(`${String(v.bytes).padStart(9)}  ${k}  (${v.package} ${v.version})`);
