// build.mjs — makes studio/lib/ (the in-browser toolchain's libraries, as
// browser ES modules) from the exact versions in ./package.json. Run inside
// the container, in a scratch directory, never on the host and never in the
// repository (node_modules is not committed):
//
//   podman exec extremers-lang mkdir -p /tmp/studio-lib
//   podman exec extremers-lang cp /workspace/studio/lib/build/package.json /workspace/studio/lib/build/build.mjs /tmp/studio-lib/
//   podman exec -w /tmp/studio-lib extremers-lang npm install --no-audit --no-fund
//   podman exec -w /tmp/studio-lib extremers-lang node build.mjs /workspace/studio/lib
//
// (build.mjs runs from the scratch directory: its imports resolve from the
// node_modules there.)
//
// What it writes (each file's version, size, sha256 and how it was made go
// to VERSIONS.json):
//
//   rollup/rollup.browser.js + bindings_wasm_bg.wasm   @rollup/browser, as published
//   babel.js          @babel/standalone's babel.min.js (UMD) wrapped as an ES
//                     module whose default export is the Babel object
//   babel-solid.js    babel-preset-solid + babel-plugin-jsx-dom-expressions +
//                     @babel/helper-module-imports (its addNamed, for the
//                     bundled-helpers plugin), bundled into one ES module by
//                     rollup; @babel/types, @babel/traverse and
//                     @babel/plugin-syntax-jsx are taken from babel.js (the
//                     same Babel), node's assert by a truthiness check
//   terser.js         terser's minify + @jridgewell/source-map, one ES module
//   csso.js           csso's dist/csso.esm.js, as published
//   plugin-html.js    @rollup/plugin-html's ES build with `path.extname` inlined
//   acorn.js          acorn's dist/acorn.mjs, as published
//   solid-js/…        solid-js's browser dist files: solid.js, store.js,
//                     web.js, universal.js (they import "solid-js" bare; the
//                     toolchain's vfs resolves it)
//   LICENSES/<pkg>.txt  each package's licence
import { rollup } from "rollup";
import commonjs from "@rollup/plugin-commonjs";
import resolve from "@rollup/plugin-node-resolve";
import json from "@rollup/plugin-json";
import { minify } from "terser";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync, copyFileSync, existsSync, rmSync } from "node:fs";
import { dirname, join, resolve as resolvePath } from "node:path";

const OUT = resolvePath(process.argv[2] || "lib");
const NM = resolvePath("node_modules");
const pkg = (name) => JSON.parse(readFileSync(join(NM, name, "package.json"), "utf8"));
const sha256 = (b) => createHash("sha256").update(b).digest("hex");

const record = {}; // out path → { package, version, from, how }
function put(rel, bytes, { pkgName, from, how }) {
  const p = join(OUT, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, bytes);
  record[rel] = { package: pkgName, version: pkg(pkgName).version, from, how, bytes: Buffer.byteLength(bytes), sha256: sha256(bytes) };
}
const copy = (rel, pkgName, from, how = "copied as published") => put(rel, readFileSync(join(NM, pkgName, from)), { pkgName, from, how });

// VERSIONS.json is shared (e.g. lib/monaco/vendor.mjs adds its `monaco` key):
// this script owns only the keys it writes below, and only the files it
// listed last time under `files` (removed here, so a dropped file goes).
const VERSIONS = join(OUT, "VERSIONS.json");
const OWN = ["recipe", "node", "packages", "builtWith", "totalBytes", "files"];
const prev = existsSync(VERSIONS) ? JSON.parse(readFileSync(VERSIONS, "utf8")) : {};
for (const f of Object.keys(prev.files || {})) rmSync(join(OUT, f), { force: true });

// ---- rollup (the browser build: ES module + its wasm, loaded next to it)
copy("rollup/rollup.browser.js", "@rollup/browser", "dist/es/rollup.browser.js");
copy("rollup/bindings_wasm_bg.wasm", "@rollup/browser", "dist/es/bindings_wasm_bg.wasm");

// ---- babel standalone, as an ES module
{
  const src = readFileSync(join(NM, "@babel/standalone/babel.min.js"), "utf8");
  const code =
    "// @babel/standalone " + pkg("@babel/standalone").version + " (babel.min.js, MIT) as an ES module: its default export is the Babel object.\n" +
    "// Generated by studio/lib/build/build.mjs; not edited by hand.\n" +
    "var module = { exports: {} }; var exports = module.exports;\n" +
    src +
    "\nexport default module.exports;\n";
  put("babel.js", code, { pkgName: "@babel/standalone", from: "babel.min.js", how: "UMD wrapped as an ES module (default export = module.exports)" });
}

// ---- one-file ES modules made with rollup
async function bundle(rel, input, { pkgName, from, how, shims = {}, externals = {} }) {
  const VIRT = "\0entry";
  const b = await rollup({
    input: VIRT,
    external: Object.keys(externals),
    plugins: [
      {
        name: "entry-and-shims",
        resolveId(id) {
          if (id === VIRT) return VIRT;
          if (Object.prototype.hasOwnProperty.call(shims, id)) return "\0shim:" + id;
          return null;
        },
        load(id) {
          if (id === VIRT) return input;
          if (id.startsWith("\0shim:")) return shims[id.slice(6)];
          return null;
        },
      },
      resolve({ browser: true, preferBuiltins: false }),
      json(),
      commonjs({ requireReturnsDefault: "auto", ignoreDynamicRequires: true }),
    ],
    onwarn(w) {
      if (w.code === "CIRCULAR_DEPENDENCY" || w.code === "THIS_IS_UNDEFINED") return;
      console.warn(`${rel}: ${w.message}`);
    },
  });
  const { output } = await b.generate({ format: "es", paths: externals, generatedCode: "es2015" });
  await b.close();
  if (output.length !== 1) throw new Error(`${rel}: ${output.length} chunks`);
  const min = await minify(output[0].code, { module: true, ecma: 2020, compress: { passes: 1 }, mangle: true, format: { comments: false } });
  const head = `// ${pkgName} ${pkg(pkgName).version} — ${how}. Generated by studio/lib/build/build.mjs; not edited by hand. Licences: LICENSES/.\n`;
  put(rel, head + min.code + "\n", { pkgName, from, how });
}

// babel-preset-solid and its plugin, on babel.js's own Babel
const BABEL = "studio-lib:babel"; // external, written as ./babel.js
const fromBabel = (expr) => `import Babel from ${JSON.stringify(BABEL)};\nexport default ${expr};\n`;
await bundle(
  "babel-solid.js",
  `export { default as presetSolid } from "babel-preset-solid";\nexport { addNamed } from "@babel/helper-module-imports";\n`,
  {
    pkgName: "babel-preset-solid",
    from: "index.js (+ babel-plugin-jsx-dom-expressions " + pkg("babel-plugin-jsx-dom-expressions").version + ", @babel/helper-module-imports " + pkg("@babel/helper-module-imports").version + ", html-entities, parse5)",
    how: "rollup (node-resolve, commonjs) + terser into one ES module; @babel/types, @babel/traverse, @babel/plugin-syntax-jsx from babel.js; node's assert replaced by a truthiness check",
    externals: { [BABEL]: "./babel.js" },
    shims: {
      "@babel/types": fromBabel("Babel.packages.types"),
      "@babel/traverse": fromBabel("Babel.packages.traverse"),
      // required as `require(...).default`: a second export makes the
      // commonjs plugin hand over the namespace, not the default
      "@babel/plugin-syntax-jsx": fromBabel('Babel.availablePlugins["syntax-jsx"]') + "export var __esModule = true;\n",
      // node's assert, as @babel/helper-module-imports uses it (a plain truthiness check)
      assert: 'export default function assert(ok, message) { if (!ok) throw new Error(message || "assertion failed"); }\n',
    },
  },
);

// terser, without its CLI
await bundle(
  "terser.js",
  // (by file path: terser's package exports don't expose lib/)
  ["transform", "mozilla-ast"].map((f) => `import ${JSON.stringify(join(NM, `terser/lib/${f}.js`))};\n`).join("") +
    `export { minify } from ${JSON.stringify(join(NM, "terser/lib/minify.js"))};\n`,
  { pkgName: "terser", from: "lib/minify.js (+ @jridgewell/source-map)", how: "rollup (node-resolve) + terser into one ES module, without the CLI" },
);

// @rollup/plugin-html, with path.extname inlined
await bundle(
  "plugin-html.js",
  `export { default } from "@rollup/plugin-html";\n`,
  {
    pkgName: "@rollup/plugin-html",
    from: "dist/es/index.js",
    how: "rollup into one ES module; node's path.extname replaced by an equivalent",
    shims: { path: 'export function extname(p) { var b = p.slice(p.lastIndexOf("/") + 1); var i = b.lastIndexOf("."); return i <= 0 ? "" : b.slice(i); }\n' },
  },
);

