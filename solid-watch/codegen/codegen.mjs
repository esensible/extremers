#!/usr/bin/env node
// solid-watch codegen: schema -> JSX types, Swift prop structs, JS schema table.
//
// Core (default; run from the package root):
//   node codegen/codegen.mjs
//     writes js/jsx.d.ts, Sources/SolidWatch/Generated/NodeProps.swift,
//     browser/props.js from schema/nodes.json
//
// App fragment (custom node types, props on core types, press handlers):
//   node codegen/codegen.mjs --fragment app.json --ts out.d.ts --swift out.swift --js out.js
//     The fragment's `name` prefixes its Swift types. Its Swift file imports
//     SolidWatch and uses the core runtime types; its JS file exports the raw
//     fragment for the browser host (mergeSchema at runtime).
//
//   --check   compare instead of write; exit 1 if any output is stale
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { mergeSchema } from "../js/schema-merge.js";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const HEADER = (src) => `Generated by solid-watch codegen from ${src}. Do not edit.`;

// ---- args -------------------------------------------------------------------
const args = process.argv.slice(2);
const opt = (k) => {
  const i = args.indexOf(k);
  return i >= 0 ? args[i + 1] : undefined;
};
const check = args.includes("--check");
const fragmentPath = opt("--fragment");

const core = JSON.parse(readFileSync(resolve(ROOT, "schema/nodes.json"), "utf8"));

// ---- naming -----------------------------------------------------------------
const upper = (s) => s.charAt(0).toUpperCase() + s.slice(1);
const camel = (s) => {
  const parts = String(s).split(/[^A-Za-z0-9]+/).filter(Boolean);
  const out = parts.map((p, i) => (i === 0 ? p.charAt(0).toLowerCase() + p.slice(1) : upper(p))).join("");
  return /^[0-9]/.test(out) ? "v" + out : out;
};
const SWIFT_RESERVED = new Set(["default", "case", "switch", "class", "struct", "enum", "func", "let", "var", "in", "is", "as", "self", "Type", "init", "return", "repeat", "where", "protocol", "extension", "import", "operator", "public", "private", "static", "true", "false", "nil"]);
const swiftIdent = (s) => (SWIFT_RESERVED.has(s) ? "`" + s + "`" : s);
const swiftCase = (prop, value) => swiftIdent((prop.swiftNames && prop.swiftNames[value]) || camel(value));
const swiftStr = (s) => JSON.stringify(String(s)); // JSON string escapes are valid Swift
const ts = (s) => JSON.stringify(s);

// Group name -> Swift struct name. Core groups: LayoutProps; a node's own props
// group (named after the node): ButtonProps; a fragment's extension of a node
// (named "frag:node"): <Frag>ButtonProps; a fragment group: <Frag><Group>Props.
function structName(group, prefix) {
  if (group.includes(":")) {
    const [frag, node] = group.split(":");
    return upper(camel(frag)) + upper(camel(node)) + "Props";
  }
  return prefix + upper(camel(group)) + "Props";
}
// Enum type for an enum prop: shared-group props by prop name (FlexDirection);
// node-own props by node + prop (ClockFormat).
function enumName(group, name, prefix, isNodeGroup) {
  if (group.includes(":")) {
    const [frag, node] = group.split(":");
    return upper(camel(frag)) + upper(camel(node)) + upper(name);
  }
  return prefix + (isNodeGroup ? upper(camel(group)) : "") + upper(name);
}

// ---- collect groups (each prop once, with the group that owns it) -----------
// Returns [{ group, struct, isNodeGroup, props: [[name, spec]] }] for the props
// defined by `owned` (the schema this file is generated for).
function groupsFor(merged, ownedNames, prefix) {
  const seen = new Map();
  for (const node of Object.values(merged.nodes)) {
    for (const [name, p] of Object.entries(node.props)) {
      if (!ownedNames(p.group, node)) continue;
      let g = seen.get(p.group);
      if (!g) {
        const isNodeGroup = !!merged.nodes[p.group] && !merged.groups[p.group];
        g = { group: p.group, struct: structName(p.group, prefix), isNodeGroup, props: new Map() };
        seen.set(p.group, g);
      }
      g.props.set(name, p);
    }
  }
  return [...seen.values()].map((g) => ({ ...g, props: [...g.props.entries()] }));
}

// ---- Swift ------------------------------------------------------------------
function swiftType(g, name, p, prefix) {
  const opt = p.default === null ? "?" : "";
  switch (p.type) {
    case "number": return "Double" + opt;
    case "string": return "String" + opt;
    case "boolean": return "Bool";
    case "enum": return enumName(g.group, name, prefix, g.isNodeGroup) + opt;
    case "dimension": return "Dimension";
    case "color": return "String" + opt;
    case "event": return "Bool";
    case "object": return p.fields ? enumName(g.group, name, prefix, g.isNodeGroup) + "?" : "PropValue?";
    case "any": return "PropValue";
    case "bytes": return "[UInt8]?";
  }
  throw new Error(p.type);
}
function swiftDefault(g, name, p, prefix) {
  const d = p.default;
  switch (p.type) {
    case "number": return d === null ? "nil" : String(d);
    case "string": case "color": return d === null ? "nil" : swiftStr(d);
    case "boolean": return d ? "true" : "false";
    case "enum": return d === null ? "nil" : "." + swiftCase(p, d);
    case "dimension":
      if (d === null) return ".undefined";
      if (d === "auto") return ".auto";
      if (typeof d === "number") return `.points(${d})`;
      return `.percent(${parseFloat(d)})`;
    case "event": return "false";
    case "object": return "nil";
    case "any": return ".null";
    case "bytes": return "nil";
  }
  throw new Error(p.type);
}
function swiftDecode(g, name, p, prefix) {
  switch (p.type) {
    case "number": return "PropDecode.number(value)";
    case "string": case "color": return "PropDecode.string(value)";
    case "boolean": return "PropDecode.bool(value)";
    case "enum": return `PropDecode.string(value).flatMap(${enumName(g.group, name, prefix, g.isNodeGroup)}.init(rawValue:))`;
    case "dimension": return `Dimension.parse(value, allowAuto: ${p.auto ? "true" : "false"})`;
    case "event": return "PropDecode.bool(value)";
    case "object": return p.fields ? `${enumName(g.group, name, prefix, g.isNodeGroup)}(value)` : "Optional(value)";
    case "any": return "Optional(value)";
    case "bytes": return "PropDecode.bytes(value)";
  }
  throw new Error(p.type);
}

function swiftEnumsAndStructs(groups, prefix) {
  const out = [];
  for (const g of groups) {
    for (const [name, p] of g.props) {
      if (p.type === "enum") {
        const en = enumName(g.group, name, prefix, g.isNodeGroup);
        out.push(`/// \`${name}\`: ${p.values.join(" | ")}`);
        out.push(`public enum ${en}: String, CaseIterable, Sendable {`);
        for (const v of p.values) out.push(`  case ${swiftCase(p, v)} = ${swiftStr(v)}`);
        out.push(`}`, ``);
      }
      if (p.type === "object" && p.fields) {
        const sn = enumName(g.group, name, prefix, g.isNodeGroup);
        out.push(`/// \`${name}\`: { ${Object.entries(p.fields).map(([k, t]) => `${k}: ${t}`).join(", ")} }`);
        out.push(`public struct ${sn}: Equatable, Sendable {`);
        for (const [k, t] of Object.entries(p.fields)) {
          if (t !== "string") throw new Error(`object field type ${t} not supported`);
          out.push(`  public var ${swiftIdent(k)}: String`);
        }
        out.push(`  /// nil unless \`value\` is an object; missing or non-string fields read as "".`);
        out.push(`  public init?(_ value: PropValue) {`);
        out.push(`    guard case .object(let o) = value else { return nil }`);
        for (const k of Object.keys(p.fields)) out.push(`    ${swiftIdent(k)} = PropDecode.string(o[${swiftStr(k)}] ?? .null) ?? ""`);
        out.push(`  }`, `}`, ``);
      }
    }
    const doc = g.isNodeGroup ? `\`${g.group}\`'s own props.` : `Props of the \`${g.group}\` group.`;
    out.push(`/// ${doc}`);
    out.push(`public struct ${g.struct}: Equatable, Sendable {`);
    for (const [name, p] of g.props) {
      if (p.doc) out.push(`  /// ${p.doc}`);
      out.push(`  public var ${swiftIdent(name)}: ${swiftType(g, name, p, prefix)} = ${swiftDefault(g, name, p, prefix)}`);
    }
    out.push(``, `  public init() {}`, ``);
    out.push(`  /// Applies one prop. \`.null\` resets it to its default; an invalid value also`);
    out.push(`  /// resets it and returns \`.invalid\`; a name this struct doesn't own returns \`.unknown\`.`);
    out.push(`  public mutating func set(_ name: String, _ value: PropValue) -> PropSetResult {`);
    out.push(`    switch name {`);
    for (const [name, p] of g.props) {
      const id = "self." + swiftIdent(name); // props may be called `name` or `value`
      const def = swiftDefault(g, name, p, prefix);
      out.push(`    case ${swiftStr(name)}:`);
      out.push(`      if value == .null { ${id} = ${def}; return .ok }`);
      out.push(`      guard let v = ${swiftDecode(g, name, p, prefix)} else { ${id} = ${def}; return .invalid }`);
      out.push(`      ${id} = v`);
      out.push(`      return .ok`);
    }
    out.push(`    default:`, `      return .unknown`, `    }`, `  }`, `}`, ``);
  }
  return out;
}

function swiftSpecTable(nodes, colors, handlers) {
  const out = [];
  out.push(`  public static let colors: [String: String] = [`);
  for (const [k, v] of Object.entries(colors)) out.push(`    ${swiftStr(k)}: ${swiftStr(v)},`);
  if (!Object.keys(colors).length) out.push(`    :`);
  out.push(`  ]`, ``);
  out.push(`  /// Native press handlers the app registers (\`button press=\`).`);
  out.push(`  public static let pressHandlers: [String] = [${Object.keys(handlers).map(swiftStr).join(", ")}]`, ``);
  out.push(`  public static let nodes: [String: NodeSpec] = [`);
  for (const n of nodes) {
    out.push(`    ${swiftStr(n.type)}: NodeSpec(type: ${swiftStr(n.type)}, children: .${n.children}, native: ${n.native}, layout: ${n.layout}, props: [`);
    for (const [name, p] of n.props) {
      const values = p.type === "enum" ? `[${p.values.map(swiftStr).join(", ")}]` : "[]";
      out.push(`      ${swiftStr(name)}: PropSpec(name: ${swiftStr(name)}, kind: .${p.kind}, type: .${p.type === "enum" ? "enumeration" : p.type}, group: ${swiftStr(p.group)}, inherits: ${!!p.inherit}, values: ${values}),`);
    }
    if (!n.props.length) out.push(`      :`);
    out.push(`    ]),`);
  }
  if (!nodes.length) out.push(`    :`);
  out.push(`  ]`);
  return out;
}

const SWIFT_RUNTIME = `/// A prop value as it crosses from JS: JSON-shaped. JS \`null\` and \`undefined\`
/// arrive as \`.null\`, which resets a prop to its default. An event prop
/// (\`onPress\`) arrives as \`.bool(true)\` when a JS handler is set.
public enum PropValue: Equatable, Sendable {
  case null
  case bool(Bool)
  case number(Double)
  case string(String)
  case array([PropValue])
  case object([String: PropValue])
}

/// A Yoga length: unset, auto, points, or percent of the parent.
public enum Dimension: Equatable, Sendable {
  case undefined
  case auto
  case points(Double)
  case percent(Double)

  /// number -> points, "auto" (if allowed), "<n>%" -> percent; else nil.
  public static func parse(_ value: PropValue, allowAuto: Bool) -> Dimension? {
    switch value {
    case .number(let d):
      return d.isFinite ? .points(d) : nil
    case .string(let s):
      if s == "auto" { return allowAuto ? .auto : nil }
      if s.hasSuffix("%"), let d = Double(s.dropLast()), d.isFinite { return .percent(d) }
      return nil
    default:
      return nil
    }
  }
}

public enum PropSetResult: Sendable {
  case unknown
  case ok
  case invalid
}

/// What a prop change invalidates.
public enum PropKind: String, Sendable {
  case layout  // Yoga style
  case measure  // text measurement: dirty the text leaf's Yoga node
  case paint  // redraw only
  case behavior  // host behaviour
  case event  // a JS handler is (un)set
}

public enum PropType: String, Sendable {
  case number, string, boolean, enumeration = "enum", dimension, color, event, object, any, bytes
}

public enum ChildKind: String, Sendable {
  case nodes  // element children
  case text  // raw strings and nested <text> spans
  case none
}

public struct PropSpec: Sendable {
  public let name: String
  public let kind: PropKind
  public let type: PropType
  public let group: String
  public let inherits: Bool
  public let values: [String]

  public init(name: String, kind: PropKind, type: PropType, group: String, inherits: Bool, values: [String]) {
    self.name = name
    self.kind = kind
    self.type = type
    self.group = group
    self.inherits = inherits
    self.values = values
  }
}

public struct NodeSpec: Sendable {
  public let type: String
  public let children: ChildKind
  /// Registered by an app fragment rather than built in.
  public let native: Bool
  /// Has a Yoga node (false for haptic).
  public let layout: Bool
  public let props: [String: PropSpec]

  public init(type: String, children: ChildKind, native: Bool, layout: Bool, props: [String: PropSpec]) {
    self.type = type
    self.children = children
    self.native = native
    self.layout = layout
    self.props = props
  }
}

public enum PropDecode {
  public static func number(_ v: PropValue) -> Double? {
    if case .number(let d) = v, d.isFinite { return d }
    return nil
  }
  public static func string(_ v: PropValue) -> String? {
    if case .string(let s) = v { return s }
    return nil
  }
  public static func bool(_ v: PropValue) -> Bool? {
    if case .bool(let b) = v { return b }
    return nil
  }
  public static func bytes(_ v: PropValue) -> [UInt8]? {
    guard case .array(let a) = v else { return nil }
    var out: [UInt8] = []
    out.reserveCapacity(a.count)
    for e in a {
      guard case .number(let d) = e, d >= 0, d <= 255, d == d.rounded() else { return nil }
      out.append(UInt8(d))
    }
    return out
  }
}

/// Colours: "#RRGGBB", "#RRGGBBAA", or a name from a schema's \`colors\`.
public enum ColorParse {
  /// 0xRRGGBBAA, or nil if \`s\` is neither hex nor a known name.
  public static func rgba(_ s: String, names: [String: String]) -> UInt32? {
    if let named = names[s] { return hex(named) }
    return hex(s)
  }
  static func hex(_ s: String) -> UInt32? {
    guard s.hasPrefix("#") else { return nil }
    let digits = s.dropFirst()
    guard digits.count == 6 || digits.count == 8, let v = UInt32(digits, radix: 16) else { return nil }
    return digits.count == 6 ? (v << 8) | 0xFF : v
  }
}
`;

function genSwiftCore(merged) {
  const groups = groupsFor(merged, (group) => !group.includes(":") && (core.groups[group] || core.nodes[group]), "");
  const nodes = Object.values(merged.nodes).map((n) => ({ ...n, props: Object.entries(n.props) }));
  return [
    `// ${HEADER("schema/nodes.json")}`,
    `// swiftlint:disable all`,
    ``,
    SWIFT_RUNTIME,
    ...swiftEnumsAndStructs(groups, ""),
    `/// The core node types and their props.`,
    `public enum CoreSchema {`,
    `  /// The font both hosts measure and draw with (README: Font).`,
    `  public static let fontFamily = ${swiftStr(core.font.family)}`,
    `  public static let fontFile = ${swiftStr(core.font.file)}`,
    `  /// Default line height = fontSize x this (hhea ascent + descent + gap over units/em).`,
    `  public static let fontLineHeightRatio: Double = ${core.font.lineHeightRatio}`,
    `  public static let fontAscentRatio: Double = ${core.font.ascent / core.font.unitsPerEm}`,
    `  public static let fontDescentRatio: Double = ${core.font.descent / core.font.unitsPerEm}`,
    `  /// Shrink-to-fit size grid and "fits" tolerance, points (README: Shrink-to-fit).`,
    `  public static let fitStep: Double = 0.5`,
    `  public static let fitEpsilon: Double = 0.001`,
    `  /// Yoga config both hosts use.`,
    `  public static let pointScaleFactor: Double = 2`,
    ``,
    ...swiftSpecTable(nodes, merged.colors, merged.pressHandlers),
    `}`,
    ``,
  ].join("\n");
}

function genSwiftFragment(merged, frag, src) {
  const prefix = upper(camel(frag.name));
  const isOwned = (group) => group.startsWith(frag.name + ":") || (frag.groups && frag.groups[group]) || (frag.nodes && frag.nodes[group]);
  const groups = groupsFor(merged, (group) => isOwned(group), prefix);
  // Spec table: the fragment's new nodes in full, plus the props it adds to core nodes.
  const newNodes = Object.values(merged.nodes).filter((n) => n.from === frag.name).map((n) => ({ ...n, props: Object.entries(n.props) }));
  const extended = Object.values(merged.nodes)
    .filter((n) => n.from !== frag.name)
    .map((n) => ({ type: n.type, props: Object.entries(n.props).filter(([, p]) => isOwned(p.group)) }))
    .filter((n) => n.props.length);
  const colors = frag.colors || {};
  const ext = [`  /// Props this fragment adds to existing node types.`, `  public static let extends: [String: [String: PropSpec]] = [`];
  for (const n of extended) {
    ext.push(`    ${swiftStr(n.type)}: [`);
    for (const [name, p] of n.props) {
      const values = p.type === "enum" ? `[${p.values.map(swiftStr).join(", ")}]` : "[]";
      ext.push(`      ${swiftStr(name)}: PropSpec(name: ${swiftStr(name)}, kind: .${p.kind}, type: .${p.type === "enum" ? "enumeration" : p.type}, group: ${swiftStr(p.group)}, inherits: ${!!p.inherit}, values: ${values}),`);
    }
    ext.push(`    ],`);
  }
  if (!extended.length) ext.push(`    :`);
  ext.push(`  ]`);
  return [
    `// ${HEADER(src)}`,
    `// swiftlint:disable all`,
    `import SolidWatch`,
    ``,
    ...swiftEnumsAndStructs(groups, prefix),
    `/// Schema fragment \`${frag.name}\`.`,
    `public enum ${prefix}Schema {`,
    ...swiftSpecTable(newNodes, colors, frag.pressHandlers || {}),
    ``,
    ...ext,
    `}`,
    ``,
  ].join("\n");
}

// ---- TypeScript -------------------------------------------------------------
function tsType(p, merged) {
  switch (p.type) {
    case "number": return "number";
    case "string": return "string";
    case "boolean": return "boolean";
    case "enum": return p.values.map(ts).join(" | ");
    case "dimension": return p.auto ? 'number | "auto" | `${number}%`' : "number | `${number}%`";
    case "color": return "Color";
    case "event": return "(payload: any) => void";
    case "object": return p.fields ? `{ ${Object.entries(p.fields).map(([k, t]) => `${k}?: ${t}`).join("; ")} }` : "Record<string, unknown>";
    case "any": return "unknown";
    case "bytes": return "number[]";
  }
  throw new Error(p.type);
}
function tsPropType(name, p) {
  if (name === "press") return "PressHandlerName";
  return tsType(p);
}
const tsIface = (group) => {
  if (group.includes(":")) {
    const [frag, node] = group.split(":");
    return upper(camel(frag)) + upper(camel(node)) + "Props";
  }
  return upper(camel(group)) + "Props";
};
const childrenType = { nodes: "JSX.Element", text: "JSX.Element", none: "never" };

function tsGroupIfaces(groups) {
  const out = [];
  for (const g of groups) {
    out.push(`export interface ${tsIface(g.group)} {`);
    for (const [name, p] of g.props) {
      if (p.doc) out.push(`  /** ${p.doc} */`);
      out.push(`  ${name}?: ${tsPropType(name, p)} | null;`);
    }
    out.push(`}`, ``);
  }
  return out;
}

function genTsCore(merged) {
  const groups = groupsFor(merged, (group) => core.groups[group] || core.nodes[group], "");
  const out = [
    `// ${HEADER("schema/nodes.json")}`,
    `import type { JSX } from "solid-js";`,
    ``,
    `/** "#RRGGBB", "#RRGGBBAA" or a colour name from a schema's colors. */`,
    `export type Color = ${["`#${string}`", ...Object.keys(merged.colors).map(ts), "(string & {})"].join(" | ")};`,
    ``,
    `/** Names of native press handlers; app fragments add to it. */`,
    `export interface PressHandlers {}`,
    `export type PressHandlerName = keyof PressHandlers extends never ? string : keyof PressHandlers;`,
    ``,
    ...tsGroupIfaces(groups),
  ];
  for (const n of Object.values(merged.nodes)) {
    const ifaces = [...new Set(Object.values(n.props).map((p) => tsIface(p.group)))];
    out.push(`/** ${n.doc} */`);
    out.push(`export interface ${upper(n.type)}Element${ifaces.length ? " extends " + ifaces.join(", ") : ""} {`);
    out.push(`  children?: ${childrenType[n.children]};`);
    out.push(`  ref?: unknown;`);
    out.push(`}`, ``);
  }
  out.push(`declare module "solid-js" {`, `  namespace JSX {`, `    interface IntrinsicElements {`);
  for (const n of Object.values(merged.nodes)) out.push(`      ${n.type}: ${upper(n.type)}Element;`);
  out.push(`    }`, `  }`, `}`, ``);
  return out.join("\n");
}

function genTsFragment(merged, frag, src) {
  const isOwned = (group) => group.startsWith(frag.name + ":") || (frag.groups && frag.groups[group]) || (frag.nodes && frag.nodes[group]);
  const groups = groupsFor(merged, isOwned, "");
  const out = [
    `// ${HEADER(src)}`,
    `import type { JSX } from "solid-js";`,
    `import type { Color } from "solid-watch/jsx";`,
    ``,
    ...tsGroupIfaces(groups),
  ];
  const newNodes = Object.values(merged.nodes).filter((n) => n.from === frag.name);
  for (const n of newNodes) {
    const ifaces = [...new Set(Object.values(n.props).map((p) => (isOwned(p.group) ? tsIface(p.group) : `import("solid-watch/jsx").${tsIface(p.group)}`)))];
    out.push(`/** ${n.doc} */`);
    out.push(`export interface ${upper(camel(n.type))}Element${ifaces.length ? " extends " + ifaces.join(", ") : ""} {`);
    out.push(`  children?: ${childrenType[n.children]};`, `  ref?: unknown;`, `}`, ``);
  }
  out.push(`declare module "solid-watch/jsx" {`);
  out.push(`  interface PressHandlers {`);
  for (const k of Object.keys(frag.pressHandlers || {})) out.push(`    ${ts(k)}: true;`);
  out.push(`  }`);
  for (const [type] of Object.entries(frag.extends || {})) {
    const ifaces = groups.filter((g) => g.group === `${frag.name}:${type}`).map((g) => tsIface(g.group));
    if (ifaces.length) out.push(`  interface ${upper(type)}Element extends ${ifaces.join(", ")} {}`);
  }
  out.push(`}`, ``);
  out.push(`declare module "solid-js" {`, `  namespace JSX {`, `    interface IntrinsicElements {`);
  for (const n of newNodes) out.push(`      ${ts(n.type)}: ${upper(camel(n.type))}Element;`);
  out.push(`    }`, `  }`, `}`, ``);
  return out.join("\n");
}

// ---- JS ---------------------------------------------------------------------
function genJs(name, value, src) {
  return `// ${HEADER(src)}\nexport const ${name} = ${JSON.stringify(value, null, 2)};\n`;
}

// ---- write ------------------------------------------------------------------
const outputs = [];
if (fragmentPath) {
  const frag = JSON.parse(readFileSync(fragmentPath, "utf8"));
  if (!frag.name) throw new Error("fragment needs a name");
  const merged = mergeSchema(core, frag);
  const src = opt("--src") || fragmentPath;
  if (opt("--ts")) outputs.push([opt("--ts"), genTsFragment(merged, frag, src)]);
  if (opt("--swift")) outputs.push([opt("--swift"), genSwiftFragment(merged, frag, src)]);
  if (opt("--js")) outputs.push([opt("--js"), genJs("fragment", frag, src)]);
} else {
  const merged = mergeSchema(core);
  outputs.push([resolve(ROOT, "js/jsx.d.ts"), genTsCore(merged)]);
  outputs.push([resolve(ROOT, "Sources/SolidWatch/Generated/NodeProps.swift"), genSwiftCore(merged)]);
  outputs.push([resolve(ROOT, "browser/props.js"), genJs("schema", core, "schema/nodes.json")]);
}

let stale = 0;
for (const [path, text] of outputs) {
  if (check) {
    const cur = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (cur !== text) {
      console.error(`stale: ${path}`);
      stale++;
    }
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
    console.log(`wrote ${path}`);
  }
}
if (stale) process.exit(1);
