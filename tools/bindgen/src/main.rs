/// A schema as JSON (postcard-schema's owned form).
fn schema_json(nt: &'static postcard_schema::schema::NamedType) -> Value {
    serde_json::to_value(OwnedNamedType::from(nt)).unwrap()
}

/// The generated files: (path under the repository root, contents).
fn files() -> Vec<(String, String)> {
    let mut out = Vec::new();
    let pretty = |v: &Value| serde_json::to_string_pretty(v).unwrap() + "\n";

    // the host protocol
    let host = host_exports();
    let generated = js::generate(&host, &header("The host protocol (extreme-protocol)."));
    out.push(("protocol-js/protocol.js".into(), generated.js));
    out.push(("protocol-js/protocol.d.ts".into(), generated.dts));
    out.push(("protocol-js/test/vectors.json".into(), pretty(&vectors::host_vectors())));
    out.push((
        "protocol-js/schema.json".into(),
        pretty(&json!({
            "Envelope": schema_json(Envelope::SCHEMA),
            "HostEvent": schema_json(HostEvent::SCHEMA),
            "ChooseView": schema_json(ChooseView::SCHEMA),
            "Manifest": schema_json(Manifest::SCHEMA),
            "GetAsset": schema_json(GetAsset::SCHEMA),
            "AssetHeader": schema_json(AssetHeader::SCHEMA),
            "BundleRequest": schema_json(BundleRequest::SCHEMA),
            "BundleResponse": schema_json(BundleResponse::SCHEMA),
        })),
    ));
    out.push((
        "protocol-swift/Sources/HostProtocol/HostProtocol.swift".into(),
        swift::generate(&host, &header("The host protocol (extreme-protocol).").replace("JS values", "Swift values")),
    ));

    // the packages: each its own view and events
    let packages: [(&str, &str, Vec<Export>, Value, Value); 2] = [
        (
            "extreme-race",
            "The race package's view and events (extreme-race).",
            vec![
                Export { name: "RaceView", schema: RaceView::SCHEMA, doc: "The race engine's view: an Envelope's `state` while race is active." },
                Export { name: "RaceEvent", schema: RaceEvent::SCHEMA, doc: "An event for the race engine: a HostEvent Engine's `bytes`." },
            ],
            vectors::race_vectors(),
            json!({ "view": schema_json(RaceView::SCHEMA), "event": schema_json(RaceEvent::SCHEMA) }),
        ),
        (
            "extreme-tune",
            "The tune package's view (extreme-tune; it takes no events).",
            vec![Export { name: "TuneView", schema: TuneView::SCHEMA, doc: "The tune engine's view: an Envelope's `state` while tune is active." }],
            vectors::tune_vectors(),
            json!({ "view": schema_json(TuneView::SCHEMA), "event": schema_json(<()>::SCHEMA) }),
        ),
    ];
    for (dir, what, exports, vectors, schema) in packages {
        let generated = js::generate(&exports, &header(what));
        out.push((format!("{dir}/protocol-js/protocol.js"), generated.js));
        out.push((format!("{dir}/protocol-js/protocol.d.ts"), generated.dts));
        out.push((format!("{dir}/protocol-js/vectors.json"), pretty(&vectors)));
        out.push((format!("{dir}/protocol-js/schema.json"), pretty(&schema)));
    }
    out
}

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
}

/// The files whose committed contents differ from what is generated now.
fn stale() -> Vec<String> {
    files()
        .into_iter()
        .filter(|(path, contents)| fs::read_to_string(root().join(path)).ok().as_ref() != Some(contents))
        .map(|(path, _)| path)
        .collect()
}

fn main() -> ExitCode {
    if std::env::args().any(|a| a == "--check") {
        let stale = stale();
        if stale.is_empty() {
            return ExitCode::SUCCESS;
        }
        eprintln!("stale: {stale:?}: run `cargo run -p extreme-bindgen`");
        return ExitCode::FAILURE;
    }
    for (path, contents) in files() {
        let path = root().join(path);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(&path, contents).unwrap();
        println!("wrote {}", path.display());
    }
    ExitCode::SUCCESS
}

#[cfg(test)]
mod tests {
    use super::*;
    use extreme_protocol::{CHOOSE, ENVELOPE_MAX};
    use vectors::{NOW, UI, envelopes};

    #[test]
    fn generated_files_are_current() {
        assert_eq!(stale(), Vec::<String>::new(), "run `cargo run -p extreme-bindgen`");
    }

    /// Sizes of the BLE `state` value (an Envelope, no BLE status) in 2026:
    /// what a central must fit in one notification (ATT MTU - 3).
    #[test]
    fn ble_state_sizes() {
        let mut largest = 0;
        for (what, active, state) in envelopes() {
            let e = Envelope { timestamp: NOW, active, ui: UI, state: &state };
            let n = postcard::to_stdvec(&e).unwrap().len();
            if active != CHOOSE || what.ends_with("no BLE") {
                eprintln!("BLE state, {what}: {n} bytes");
                largest = largest.max(n);
            }
            assert!(n <= ENVELOPE_MAX, "{what}: {n}");
        }
        // CoreBluetooth's usual MTU (185) carries every one in a notification
        assert!(largest <= 182, "{largest}");
    }
}
