//! Generates the clients' bindings from the Rust types' postcard schemas
//! (postcard-schema's `#[derive(Schema)]`), plus golden vectors from the
//! Rust encoder for the JS tests:
//!
//! - the host protocol (extreme-protocol: `Envelope`, `HostEvent`,
//!   `ChooseView`, `Manifest`, the bulk channel's and the bundles'
//!   messages): `protocol-js/` (JS, TypeScript, vectors,
//!   schema.json) and `protocol-swift/` (Swift, for the watch app);
//! - each package's own view and events: `<package>/protocol-js/`.
//!
//!     cargo run -p extreme-bindgen            # write them
//!     cargo run -p extreme-bindgen -- --check # fail if any is stale
//!
//! `cargo test` fails too when the committed files are stale. The packages'
//! bundles import the generated files, so they are committed rather than
//! written by a build script.

mod js;
mod js_shape;
mod swift;
mod vectors;

use std::{fs, path::PathBuf, process::ExitCode};

use extreme_protocol::{AssetHeader, BundleRequest, BundleResponse, ChooseView, Envelope, GetAsset, HostEvent, Manifest};
use extreme_race::{RaceEvent, RaceView};
use extreme_tune::TuneView;
use postcard_schema::{Schema, schema::owned::OwnedNamedType};
use serde_json::{Value, json};

use js::Export;

fn header(what: &str) -> String {
    format!(
        "// GENERATED by tools/bindgen (`cargo run -p extreme-bindgen`) from the\n\
         // Rust types' postcard schemas: do not edit. {what} The wire format and\n\
         // the JS values are described in tools/bindgen/src/js.rs and README.md."
    )
}

