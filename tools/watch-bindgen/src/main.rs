/// A package's stable id: FNV-1a 32-bit of its name. Choose is 0.
pub type PackageId = u32;

pub const CHOOSE: PackageId = 0;

pub fn package_id(name: &str) -> PackageId {
    let mut h: u32 = 0x811c_9dc5;
    for b in name.bytes() {
        h ^= b as u32;
        h = h.wrapping_mul(0x0100_0193);
    }
    h
}

/// Host -> client: the `state` characteristic (BLE) / a websocket frame.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, Schema)]
pub struct Envelope {
    /// The device clock at send, epoch ms.
    pub timestamp: u64,
    pub active: PackageId,
    pub ui_hash: [u8; 8],
    /// The active package's postcard view bytes (Choose: `ChooseView`).
    pub state: Vec<u8>,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, Schema)]
pub struct PackageInfo {
    pub id: PackageId,
    pub name: String,
    pub version: u16,
}

/// Choose's view: the installed packages (BLE status on the websocket only).
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, Schema)]
pub struct ChooseView {
    pub packages: Vec<PackageInfo>,
    pub ble: Option<BleStatusView>,
}

/// Client -> host: the `event` characteristic (BLE, never `Ble`) / a frame.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize, Schema)]
pub enum HostEvent {
    Select(PackageId),
    SelectDefault,
    Engine { package: PackageId, bytes: Vec<u8> },
    Ble(BleCommand),
}

const HEADER: &str = "// GENERATED by tools/watch-bindgen (`cargo run -p extreme-watch-bindgen`)\n\
// from the Rust types' postcard schemas: do not edit. The wire format and\n\
// the JS values are described in tools/bindgen/src/js.rs.";

/// A device clock in 2026, epoch ms.
const NOW: u64 = 1_790_000_000_123;
const MAX_SAFE: u64 = (1 << 53) - 1;

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

fn bytes<T: Serialize>(value: &T) -> Vec<u8> {
    postcard::to_stdvec(value).unwrap()
}

fn vector<T: Serialize>(ty: &str, what: &str, value: &T) -> Value {
    json!({ "type": ty, "what": what, "hex": hex(&bytes(value)), "value": to_js(value).unwrap() })
}

fn race_views() -> Vec<(String, RaceView)> {
    let lines = [
        ("no line", LineView::None),
        ("stbd set", LineView::Stbd),
        ("port set", LineView::Port),
        ("line both", LineView::Both { cross: 47, time: NOW + 25_657 }),
    ];
    let mut out = Vec::new();
    for (what, line) in lines {
        out.push((format!("active, {what}"), RaceView { speed: 6.4, phase: Phase::Active { line } }));
        out.push((
            format!("in sequence, {what}"),
            RaceView { speed: 23.2, phase: Phase::InSequence { start_time: NOW + 300_000, line } },
        ));
    }
    out.push(("racing".into(), RaceView { speed: 17.5, phase: Phase::Racing { start_time: NOW - 61_000, heading: 253.0 } }));
    out.push((
        "in sequence at the largest times".into(),
        RaceView {
            speed: 655.35,
            phase: Phase::InSequence { start_time: MAX_SAFE, line: LineView::Both { cross: 100, time: MAX_SAFE } },
        },
    ));
    out
}

fn race_events() -> Vec<(&'static str, RaceEvent)> {
    vec![
        ("line stbd", RaceEvent::LineStbd),
        ("line port", RaceEvent::LinePort),
        ("bump +600 s, tapped at NOW", RaceEvent::BumpSeq { seconds: 600, timestamp: NOW }),
        ("bump -300 s, tapped 1.5 s before NOW", RaceEvent::BumpSeq { seconds: -300, timestamp: NOW - 1500 }),
        ("sync", RaceEvent::BumpSeq { seconds: 0, timestamp: NOW }),
        ("finish", RaceEvent::RaceFinish),
    ]
}

fn tune_views() -> Vec<(String, TuneView)> {
    [(0.0, 0.0, 0.0), (6.4, 0.5, -12.3), (655.35, 327.67, 180.0), (25.5, -12.34, 45.6)]
        .into_iter()
        .map(|(speed, speed_dev, heading_dev)| {
            (format!("{speed} {speed_dev} {heading_dev}"), TuneView { speed, speed_dev, heading_dev })
        })
        .collect()
}

fn choose_views() -> Vec<(&'static str, ChooseView)> {
    let info = |name: &str, version| PackageInfo { id: package_id(name), name: name.into(), version };
    let addr = [0x10, 0x96, 0x8e, 0xa3, 0xbd, 0xd0];
    vec![
        ("nothing installed", ChooseView { packages: vec![], ble: None }),
        ("race and tune", ChooseView { packages: vec![info("race", 1), info("tune", 3)], ble: None }),
        (
            "with BLE status (websocket only)",
            ChooseView {
                packages: vec![info("race", 1)],
                ble: Some(BleStatusView {
                    addr,
                    pair_ms: 117_000,
                    bonds: heapless::Vec::from_slice(&[addr]).unwrap(),
                    max_bonds: 4,
                    note: BleNote::Paired(addr),
                }),
            },
        ),
        ("a long name, UTF-8", ChooseView { packages: vec![info("Wellen\u{fc}bung", 65535)], ble: None }),
    ]
}

const HASH: [u8; 8] = [0x8a, 0x01, 0xff, 0x00, 0x7f, 0x80, 0x10, 0xee];

fn envelopes() -> Vec<(String, Envelope)> {
    let mut out = Vec::new();
    for (what, view) in choose_views().into_iter().take(2) {
        out.push((format!("choose, {what}"), Envelope { timestamp: NOW, active: CHOOSE, ui_hash: [0; 8], state: bytes(&view) }));
    }
    for (what, view) in race_views() {
        out.push((format!("race, {what}"), Envelope { timestamp: NOW, active: package_id("race"), ui_hash: HASH, state: bytes(&view) }));
    }
    for (what, view) in tune_views() {
        out.push((format!("tune, {what}"), Envelope { timestamp: NOW, active: package_id("tune"), ui_hash: [0xff; 8], state: bytes(&view) }));
    }
    for timestamp in [0, 127, 128, MAX_SAFE] {
        out.push((
            format!("timestamp {timestamp}, unknown package, empty state"),
            Envelope { timestamp, active: u32::MAX, ui_hash: [1, 2, 3, 4, 5, 6, 7, 8], state: vec![] },
        ));
    }
    // a state longer than 127 bytes: a two-byte length
    out.push((
        "200-byte state".into(),
        Envelope { timestamp: NOW, active: 1, ui_hash: HASH, state: (0..200).map(|i| i as u8).collect() },
    ));
    out
}

fn host_events() -> Vec<(String, HostEvent)> {
    let mut out = vec![
        ("select race".to_string(), HostEvent::Select(package_id("race"))),
        ("select choose".to_string(), HostEvent::Select(CHOOSE)),
        ("select default".to_string(), HostEvent::SelectDefault),
        ("ble pair (websocket only)".to_string(), HostEvent::Ble(BleCommand::Pair)),
    ];
    for (what, event) in race_events() {
        out.push((format!("race {what}"), HostEvent::Engine { package: package_id("race"), bytes: bytes(&event) }));
    }
    out
}

struct Binding {
    dir: &'static str,
    file: &'static str,
    exports: Vec<Export>,
    vectors: Vec<Value>,
}

fn bindings() -> Vec<Binding> {
    let mut host = Vec::new();
    for (what, e) in envelopes() {
        host.push(vector("Envelope", &what, &e));
    }
    for (what, e) in host_events() {
        host.push(vector("HostEvent", &what, &e));
    }
    for (what, v) in choose_views() {
        host.push(vector("ChooseView", what, &v));
    }
    let mut race = Vec::new();
    for (what, v) in race_views() {
        race.push(vector("RaceView", &what, &v));
    }
    for (what, e) in race_events() {
        race.push(vector("RaceEvent", what, &e));
    }
    let tune = tune_views().iter().map(|(what, v)| vector("TuneView", what, v)).collect();
    vec![
        Binding {
            dir: "host-js",
            file: "host",
            exports: vec![
                Export { name: "Envelope", schema: Envelope::SCHEMA, doc: "A state from the host (BLE `state` value, websocket frame)." },
                Export { name: "HostEvent", schema: HostEvent::SCHEMA, doc: "An event to the host (BLE `event` value, websocket frame)." },
                Export { name: "ChooseView", schema: ChooseView::SCHEMA, doc: "Choose's view: an Envelope's `state` while Choose is active." },
            ],
            vectors: host,
        },
        Binding {
            dir: "extreme-race/protocol-js",
            file: "race",
            exports: vec![
                Export { name: "RaceView", schema: RaceView::SCHEMA, doc: "The race package's view: an Envelope's `state`." },
                Export { name: "RaceEvent", schema: RaceEvent::SCHEMA, doc: "A race event: a HostEvent Engine's `bytes`." },
            ],
            vectors: race,
        },
        Binding {
            dir: "extreme-tune/protocol-js",
            file: "tune",
            exports: vec![Export { name: "TuneView", schema: TuneView::SCHEMA, doc: "The tune package's view: an Envelope's `state`." }],
            vectors: tune,
        },
    ]
}

fn swift_bytes(b: &[u8]) -> String {
    let items: Vec<String> = b.iter().map(|x| format!("0x{x:02x}")).collect();
    format!("[{}]", items.join(", "))
}

/// Envelope and HostEvent vectors for the shell's native decoder tests.
fn swift_vectors() -> String {
    let mut s = String::from(
        "// GENERATED by tools/watch-bindgen (`cargo run -p extreme-watch-bindgen`):\n\
         // postcard bytes from the Rust encoder of the host contract's types.\n\n\
         enum EnvelopeVectors {\n",
    );
    s.push_str("  struct Envelope {\n    let what: String\n    let bytes: [UInt8]\n    let timestamp: UInt64\n    let active: UInt32\n    let uiHash: [UInt8]\n    let state: [UInt8]\n  }\n\n");
    s.push_str("  struct Event {\n    let what: String\n    let bytes: [UInt8]\n  }\n\n");
    let _ = writeln!(s, "  static let race: UInt32 = {}", package_id("race"));
    let _ = writeln!(s, "  static let tune: UInt32 = {}\n", package_id("tune"));
    s.push_str("  static let envelopes: [Envelope] = [\n");
    for (what, e) in envelopes() {
        let _ = writeln!(
            s,
            "    Envelope(what: {what:?}, bytes: {}, timestamp: {}, active: {}, uiHash: {}, state: {}),",
            swift_bytes(&bytes(&e)),
            e.timestamp,
            e.active,
            swift_bytes(&e.ui_hash),
            swift_bytes(&e.state)
        );
    }
    s.push_str("  ]\n\n  static let selectDefault: [UInt8] = ");
    s.push_str(&swift_bytes(&bytes(&HostEvent::SelectDefault)));
    s.push_str("\n\n  static let events: [Event] = [\n");
    for (what, e) in host_events() {
        let _ = writeln!(s, "    Event(what: {what:?}, bytes: {}),", swift_bytes(&bytes(&e)));
    }
    s.push_str("  ]\n}\n");
    s
}

fn files() -> Vec<(String, String)> {
    let mut out = Vec::new();
    for b in bindings() {
        let g = js::generate(&b.exports, HEADER);
        out.push((format!("{}/{}.js", b.dir, b.file), g.js));
        out.push((format!("{}/{}.d.ts", b.dir, b.file), g.dts));
        let v = json!({
            "doc": "Written by tools/watch-bindgen from the Rust types: hex = postcard bytes from the Rust encoder, value = the JS value they decode to.",
            "vectors": b.vectors,
        });
        out.push((format!("{}/test/vectors.json", b.dir), serde_json::to_string_pretty(&v).unwrap() + "\n"));
    }
    out.push(("watch-app/ExtremersTests/EnvelopeVectors.swift".into(), swift_vectors()));
    out
}

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn stale() -> Vec<String> {
    files()
        .into_iter()
        .filter(|(path, contents)| fs::read_to_string(root().join(path)).ok().as_ref() != Some(contents))
        .map(|(path, _)| path)
        .collect()
}

fn main() -> ExitCode {
    if std::env::args().any(|a| a == "--check") {
        let stale = stale();
        if stale.is_empty() {
            return ExitCode::SUCCESS;
        }
        eprintln!("stale: {stale:?}: run `cargo run -p extreme-watch-bindgen`");
        return ExitCode::FAILURE;
    }
    for (path, contents) in files() {
        let path = root().join(path);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(&path, contents).unwrap();
        println!("wrote {}", path.display());
    }
    ExitCode::SUCCESS
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_files_are_current() {
        assert_eq!(stale(), Vec::<String>::new(), "run `cargo run -p extreme-watch-bindgen`");
    }

    /// FNV-1a 32 reference values.
    #[test]
    fn package_ids() {
        assert_eq!(package_id(""), 0x811c_9dc5);
        assert_eq!(package_id("a"), 0xe40c_292c);
        assert_eq!(package_id("foobar"), 0xbf9c_f968);
    }

    #[test]
    fn host_event_wire() {
        assert_eq!(bytes(&HostEvent::SelectDefault), [1]);
        assert_eq!(bytes(&HostEvent::Select(5)), [0, 5]);
        assert_eq!(bytes(&HostEvent::Engine { package: 1, bytes: vec![3] }), [2, 1, 1, 3]);
    }
}
