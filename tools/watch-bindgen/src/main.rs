//! Interim generator for the watch shell (host-contract.md): the host
//! envelope bindings (`host-js/`) and each package's own view and event
//! bindings (`extreme-race/protocol-js/`, `extreme-tune/protocol-js/`), with
//! golden vectors from the Rust encoder, plus the Swift test vectors for the
//! shell's native envelope decoder (`watch-app/ExtremersTests/`).
//!
//! The host types below are the contract's, written out here until the
//! package host (its own crate and bindgen) lands; then this tool goes and
//! the files are regenerated from the host's types. The JS generator is
//! tools/bindgen's, shared by path.
//!
//!     cargo run -p extreme-watch-bindgen            # write the files
//!     cargo run -p extreme-watch-bindgen -- --check # fail if one is stale

#[path = "../../bindgen/src/js.rs"]
