#!/bin/sh
# Builds everything the studio takes from this repository into studio/vendor/
# (generated, committed; the studio never reaches outside its prefix):
#
#   engine-wasm/  engine/wasm, wasm-bindgen --target web (wasm-opt -Oz when
#                 binaryen is installed)
#   runtimes/     the client runtimes at their repository paths: protocol-js,
#                 client-common, wire/js (codec.js and compile.js are UMD; each
#                 also as <name>.esm.js, an ES module whose default export is
#                 its module.exports), solid-watch/js/{index,renderer}.js
#                 (the universal renderer a watch bundle imports as
#                 "solid-watch") and solid-watch/test/driver.js (the
#                 recording host the studio's toolchain tests replay with)
#   watch-host/   solid-watch's browser host (solid-watch/browser/harness.js
#                 shows what a page needs): browser/{dom-host,shadow,
#                 text-layout,props}.js, js/schema-merge.js, the font,
#                 yoga-layout's dist/ (MIT; imported bare as "yoga-layout": the
#                 page maps it to yoga-layout/src/index.js), the extremers fragment
#                 (extremers.schema.json, extremers-props.js)
#   examples/race/ Race's engine directory, Kindle and watch sources, and the
#                 watch fixtures (script.json, log.jsonl)
#   fixtures/     what the studio's tests hold the wasm to:
#                 race.samples.expected.json and race.layout.json (engine/wasm's
#                 golden files, checked current by its cargo test here),
#                 race.pack/ (target/packages/race/, extreme-pack's inputs)
#                 and race.bundle (extreme-pack's bundle of them)
#   SOURCES.json  the monorepo commit, the toolchain, and each file's sha256
#                 and where it came from
#
# Runs in the dev container (cargo with wasm32-unknown-unknown, wasm-bindgen
# matching engine/wasm's Cargo.lock, node; binaryen optional), from anywhere:
#
#   podman exec -e STUDIO_SOURCE_SHA=$(git rev-parse HEAD) -w /workspace \
#       extremers-lang sh tools/studio-vendor/vendor.sh
#
# STUDIO_SOURCE_SHA names the commit (git can't run in a container holding a
# worktree whose .git is outside it); without it, git is asked, else
# "unknown". Idempotent: the same sources give the same studio/vendor/. No
# network (npm ci is only needed once, for extreme-pack's client builds).
set -eu

ROOT=$(cd "$(dirname "$0")/../.." && pwd)
OUT="$ROOT/studio/vendor"
SHA=${STUDIO_SOURCE_SHA:-$(git -C "$ROOT" rev-parse HEAD 2>/dev/null || echo unknown)}

# Race's bundle and its inputs, current with the sources
(cd "$ROOT" && cargo run --quiet -p extreme-pack -- --out target/packages --bundle)

# engine/wasm: its tests (the golden files current), then the module
(cd "$ROOT/engine/wasm" && cargo test --quiet)
(cd "$ROOT/engine/wasm" && STUDIO_SOURCE_SHA="$SHA" cargo build --quiet --release --target wasm32-unknown-unknown)

rm -rf "$OUT"
mkdir -p "$OUT"
LIST="$OUT/.sources"
: > "$LIST"

# copy SRC (from the root) DEST (under vendor/), recording where it came from
copy() {
    mkdir -p "$(dirname "$OUT/$2")"
    cp "$ROOT/$1" "$OUT/$2"
    printf '%s\t%s\n' "$2" "$1" >> "$LIST"
}

# copy_dir SRC DEST: every file under SRC
copy_dir() {
    (cd "$ROOT/$1" && find . -type f | LC_ALL=C sort) | while read -r f; do
        f=${f#./}
        copy "$1/$f" "$2/$f"
    done
}

# esm SRC DEST: the UMD file SRC as an ES module
esm() {
    mkdir -p "$(dirname "$OUT/$2")"
    {
        printf '// Generated by tools/studio-vendor/vendor.sh from %s: the module as an\n' "$1"
        printf '// ES module, whose default export is its module.exports.\n'
        printf 'var module = { exports: {} };\n'
        cat "$ROOT/$1"
        printf '\nexport default module.exports;\n'
    } > "$OUT/$2"
    printf '%s\t%s (as an ES module)\n' "$2" "$1" >> "$LIST"
}

# ---- engine-wasm ----
WASM="$ROOT/engine/wasm/target/wasm32-unknown-unknown/release/engine_wasm.wasm"
wasm-bindgen --target web --out-dir "$OUT/engine-wasm" "$WASM"
if command -v wasm-opt > /dev/null; then
    wasm-opt -Oz "$OUT/engine-wasm/engine_wasm_bg.wasm" -o "$OUT/engine-wasm/engine_wasm_bg.wasm"
    OPT=$(wasm-opt --version)
else
    echo "vendor.sh: no wasm-opt (binaryen): engine-wasm left unoptimised" >&2
    OPT=none
fi
for f in engine_wasm.js engine_wasm.d.ts engine_wasm_bg.wasm engine_wasm_bg.wasm.d.ts; do
    printf '%s\t%s\n' "engine-wasm/$f" "engine/wasm (wasm-bindgen --target web)" >> "$LIST"
done

# ---- runtimes ----
copy protocol-js/protocol.js runtimes/protocol-js/protocol.js
for f in host confirm confirm-place; do
    copy "client-common/$f.js" "runtimes/client-common/$f.js"
done
for f in codec compile rollup; do
    copy "wire/js/$f.js" "runtimes/wire/js/$f.js"
done
for f in codec compile; do
    esm "wire/js/$f.js" "runtimes/wire/js/$f.esm.js"
done
# solid-watch's universal renderer ("solid-watch" in a watch bundle, built by
# studio/toolchain) and the recording host that replays a bundle in its tests
for f in index renderer; do
    copy "solid-watch/js/$f.js" "runtimes/solid-watch/js/$f.js"
done
copy solid-watch/test/driver.js runtimes/solid-watch/test/driver.js

# ---- watch-host ----
for f in dom-host shadow text-layout props; do
    copy "solid-watch/browser/$f.js" "watch-host/browser/$f.js"
done
copy solid-watch/js/schema-merge.js watch-host/js/schema-merge.js
copy solid-watch/fonts/Inter-roman.ttf watch-host/fonts/Inter-roman.ttf
copy solid-watch/fonts/LICENSE-Inter.txt watch-host/fonts/LICENSE-Inter.txt
# its dist/ (git ignores dist/ directories), relative imports kept
copy_dir solid-watch/node_modules/yoga-layout/dist watch-host/yoga-layout
copy watch-js/extremers.schema.json watch-host/extremers.schema.json
copy watch-js/generated/extremers-props.js watch-host/extremers-props.js

# ---- examples/race ----
for f in engine.expr state.schema.json view.schema.json event.schema.json samples.json interface.json view.desc event.desc; do
    copy "engine/race/$f" "examples/race/engine/$f"
done
copy_dir extreme-race/client-js/src examples/race/client-js/src
copy_dir extreme-race/watch-js/src examples/race/watch-js/src
copy extreme-race/watch-js/fixtures/script.json examples/race/watch-js/fixtures/script.json
copy extreme-race/watch-js/fixtures/log.jsonl examples/race/watch-js/fixtures/log.jsonl

# ---- fixtures ----
copy engine/wasm/fixtures/race.samples.expected.json fixtures/race.samples.expected.json
copy engine/wasm/fixtures/race.layout.json fixtures/race.layout.json
copy_dir target/packages/race fixtures/race.pack
copy target/packages/race.bundle fixtures/race.bundle

# ---- SOURCES.json ----
node "$ROOT/tools/studio-vendor/sources.mjs" "$OUT" "$SHA" \
    "$(rustc --version)" "$(wasm-bindgen --version)" "$OPT" "$(node --version)"
rm "$LIST"

echo "studio/vendor: engine_wasm_bg.wasm $(wc -c < "$OUT/engine-wasm/engine_wasm_bg.wasm") bytes; source $SHA"
